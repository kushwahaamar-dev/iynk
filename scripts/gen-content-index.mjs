#!/usr/bin/env node
// Content registry generator (D4).
//
//   node scripts/gen-content-index.mjs              scan src/content/{boards,robotics,drones}/*.ts and
//                                                   write src/content/index.generated.ts (only when it changes)
//   node scripts/gen-content-index.mjs --check      also load every item and check id, lab and text keys; exit 1 on problems
//   node scripts/gen-content-index.mjs --emit board/uno-r3
//                                                   print { meta, data, en } as JSON for the figure build (SL.data)
//
// Items are loaded with Node's built-in TypeScript type stripping (Node >= 22.18 / 24), so content
// modules may only use erasable syntax and `import type`.

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

// Item modules are .ts files in a package without "type": "module"; Node warns once per file. Keep stdout and stderr clean.
const warn = process.emitWarning.bind(process);
process.emitWarning = (w, ...rest) => (String(w?.message ?? w).includes('Module type of') ? undefined : warn(w, ...rest));

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const contentDir = join(root, 'src', 'content');
const outFile = join(contentDir, 'index.generated.ts');

const LABS = [
  { lab: 'board', dir: 'boards', ids: 'BOARD_IDS', meta: 'BOARDS', type: 'BoardContent', idType: 'BoardId', fn: 'Board' },
  { lab: 'robotics', dir: 'robotics', ids: 'ROBOTICS_IDS', meta: 'ROBOTICS', type: 'RoboticsContent', idType: 'RoboticsId', fn: 'Robotics' },
  { lab: 'drone', dir: 'drones', ids: 'DRONE_IDS', meta: 'DRONES', type: 'DroneContent', idType: 'DroneId', fn: 'Drone' },
];

const loadIds = () => import(pathToFileURL(join(contentDir, 'ids.ts')).href);

function scan(dir) {
  const full = join(contentDir, dir);
  if (!existsSync(full)) return [];
  return readdirSync(full)
    .filter((f) => f.endsWith('.ts') && !f.endsWith('.d.ts') && !f.includes('.test.') && !f.startsWith('_'))
    .map((f) => f.slice(0, -3))
    .sort();
}

function render(found) {
  const q = (s) => `'${s}'`;
  const out = [
    '// Generated by scripts/gen-content-index.mjs. Do not edit; run `node scripts/gen-content-index.mjs`.',
    "import type { BoardContent, DroneContent, RoboticsContent } from './schema';",
    "import type { BoardId, DroneId, RoboticsId } from './ids';",
    '',
    'type Loader<T> = () => Promise<{ default: T }>;',
    '',
  ];
  for (const L of LABS) {
    const items = found[L.lab];
    out.push(`export const ${L.lab}Loaders: Partial<Record<${L.idType}, Loader<${L.type}>>> = {`);
    for (const id of items) out.push(`  ${q(id)}: () => import(${q(`./${L.dir}/${id}`)}),`);
    out.push('};', '');
  }
  out.push('/** Item ids that have a data module today, in figure order. */');
  out.push('export const AVAILABLE: { board: readonly BoardId[]; robotics: readonly RoboticsId[]; drone: readonly DroneId[] } = {');
  for (const L of LABS) out.push(`  ${L.lab}: [${found[L.lab].map(q).join(', ')}],`);
  out.push('};', '');
  for (const L of LABS) {
    out.push(`export async function load${L.fn}(id: ${L.idType}): Promise<${L.type} | null> {`);
    out.push(`  const load = ${L.lab}Loaders[id];`);
    out.push('  return load ? (await load()).default : null;');
    out.push('}', '');
  }
  return out.join('\n');
}

async function collect() {
  const ids = await loadIds();
  const found = {};
  const problems = [];
  for (const L of LABS) {
    const known = ids[L.ids];
    const files = scan(L.dir);
    for (const f of files) if (!known.includes(f)) problems.push(`src/content/${L.dir}/${f}.ts: "${f}" is not in ${L.ids} (src/content/ids.ts)`);
    found[L.lab] = known.filter((id) => files.includes(id));
  }
  return { ids, found, problems };
}

function flattenKeys(obj, prefix = '', acc = new Set()) {
  for (const [k, v] of Object.entries(obj ?? {})) {
    const key = prefix ? `${prefix}.${k}` : k;
    if (v && typeof v === 'object' && !Array.isArray(v)) flattenKeys(v, key, acc);
    else acc.add(key);
  }
  return acc;
}

function readEn(dir, id) {
  const p = join(root, 'src', 'i18n', 'content', 'en', dir, `${id}.json`);
  return existsSync(p) ? JSON.parse(readFileSync(p, 'utf8')) : null;
}

// A string in item data is a text key when it is a top-level key or starts with a section prefix
// (docs/ARCHITECTURE.md, content JSON key scheme). Everything else is a literal (pin names, code, units).
const TOP_KEYS = new Set(['title', 'tagline', 'overview', 'sub', 'hint', 'noun', 'practice']);
const SECTIONS = [
  'mcu', 'power', 'pins', 'leds', 'controls', 'displays', 'parts', 'variants', 'wireables', 'failures', 'assembly',
  'lessons', 'modes', 'steps', 'faults', 'status', 'current', 'tasks', 'quizzes', 'design', 'build', 'wiring', 'tests',
  'firmware', 'flight', 'courses',
];
const KEY_RE = new RegExp(`^(${SECTIONS.join('|')})\\.[A-Za-z0-9_-]+(\\.[A-Za-z0-9_-]+)*$`);
const isTextKey = (s) => TOP_KEYS.has(s) || KEY_RE.test(s);

function textKeys(node, path = [], acc = []) {
  if (typeof node === 'string') {
    if (isTextKey(node)) acc.push({ at: path.join('.'), key: node });
  } else if (Array.isArray(node)) {
    node.forEach((v, i) => textKeys(v, [...path, i], acc));
  } else if (node && typeof node === 'object') {
    for (const [k, v] of Object.entries(node)) {
      // A status field's `key` is a path into the figure's state (`leds.L`), never a text key.
      if (k === 'key') continue;
      if (typeof v === 'string' && (k === 'source' || k === 'solution' || k === 'code')) {
        for (const m of v.matchAll(/\{\{t:([^}]+)\}\}/g)) acc.push({ at: [...path, k].join('.'), key: m[1] });
      } else textKeys(v, [...path, k], acc);
    }
  }
  return acc;
}

async function loadItem(dir, id) {
  const href = pathToFileURL(join(contentDir, dir, `${id}.ts`)).href;
  return (await import(href)).default;
}

async function check() {
  const { found, problems } = await collect();
  for (const L of LABS) {
    for (const id of found[L.lab]) {
      const where = `src/content/${L.dir}/${id}.ts`;
      let data;
      try {
        data = await loadItem(L.dir, id);
      } catch (e) {
        problems.push(`${where}: cannot load (${e.message.split('\n')[0]})`);
        continue;
      }
      if (!data || typeof data !== 'object') { problems.push(`${where}: no default export`); continue; }
      if (data.id !== id) problems.push(`${where}: id is "${data.id}", expected "${id}"`);
      if (data.lab !== L.lab) problems.push(`${where}: lab is "${data.lab}", expected "${L.lab}"`);
      const en = readEn(L.dir, id);
      if (!en) { problems.push(`src/i18n/content/en/${L.dir}/${id}.json: missing`); continue; }
      const have = flattenKeys(en);
      const missing = [...new Set(textKeys(data).filter((t) => !have.has(t.key)).map((t) => `${t.key} (${t.at})`))];
      for (const m of missing.slice(0, 40)) problems.push(`${where}: text key not in en JSON: ${m}`);
      if (missing.length > 40) problems.push(`${where}: ... and ${missing.length - 40} more missing keys`);
    }
  }
  return problems;
}

async function emit(spec) {
  const [labName, id] = String(spec).split('/');
  const L = LABS.find((x) => x.lab === labName || x.dir === labName);
  if (!L || !id) throw new Error(`--emit wants <lab>/<id>, e.g. board/uno-r3; got "${spec}"`);
  const ids = await loadIds();
  if (!ids[L.ids].includes(id)) throw new Error(`"${id}" is not in ${L.ids}`);
  const data = existsSync(join(contentDir, L.dir, `${id}.ts`)) ? await loadItem(L.dir, id) : null;
  process.stdout.write(JSON.stringify({ lab: L.lab, id, meta: ids[L.meta][id], data, en: readEn(L.dir, id) ?? {} }));
}

const args = process.argv.slice(2);
try {
  if (args[0] === '--emit') {
    await emit(args[1]);
  } else {
    const { found, problems } = await collect();
    const next = render(found);
    const prev = existsSync(outFile) ? readFileSync(outFile, 'utf8') : '';
    if (prev !== next) writeFileSync(outFile, next);
    const counts = LABS.map((L) => `${found[L.lab].length} ${L.dir}`).join(', ');
    console.log(`content index: ${counts}${prev === next ? ' (unchanged)' : ' (written)'}`);
    const all = args.includes('--check') ? [...new Set([...problems, ...(await check())])] : problems;
    for (const p of all) console.warn(`content: ${p}`);
    if (args.includes('--check') && all.length) process.exit(1);
  }
} catch (e) {
  console.error(`gen-content-index: ${e.message}`);
  process.exit(1);
}

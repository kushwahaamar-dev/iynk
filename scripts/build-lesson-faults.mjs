#!/usr/bin/env node
// Builds content/projects/boards/faults.ts (T-B12-21): for every lesson template the catalogue failures of its own
// circuit, and for every board all its failures in catalogue order.
//
//   node scripts/build-lesson-faults.mjs [--check]
//
// With `--check` it writes nothing and compares the file on disk. Exit 0 when done (or when the file matches),
// 1 on a difference or a failed load, 2 on bad arguments.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { listItems, loadItem } from './convert-io.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, 'content', 'projects', 'boards', 'faults.ts');

/** The circuit a failure builds in the figure, if it is one of a lesson's circuit faults. */
function failureCircuit(failure) {
  const state = failure.figure.type === 'set' ? failure.figure.state : null;
  return typeof state?.circuit === 'string' ? state.circuit : null;
}

export function buildTables() {
  const lessons = {};
  const boards = {};
  for (const { id } of listItems().filter((item) => item.lab === 'board')) {
    const { data } = loadItem('board', id);
    boards[id] = data.failures.map((failure) => failure.id);
    for (const lesson of data.lessons) {
      const own = lesson.circuit ? data.failures.filter((failure) => failureCircuit(failure) === lesson.circuit) : [];
      lessons[`prj_${id}-${lesson.id}`] = { own: own.map((failure) => failure.id) };
    }
  }
  return { lessons, boards };
}

export function tablesText({ lessons, boards }) {
  const rows = (table) => Object.entries(table).map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`);
  return [
    '// Generated by scripts/build-lesson-faults.mjs. Do not edit; run `node scripts/build-lesson-faults.mjs`.',
    '',
    'export const LESSON_FAULTS: Readonly<Record<string, { own: readonly string[] }>> = {',
    ...rows(lessons),
    '};',
    '',
    'export const BOARD_FAULTS: Readonly<Record<string, readonly string[]>> = {',
    ...rows(boards),
    '};',
    '',
  ].join('\n');
}

function main(argv) {
  if (argv.some((arg) => arg !== '--check')) {
    console.error('usage: node scripts/build-lesson-faults.mjs [--check]');
    return 2;
  }
  const text = tablesText(buildTables());
  if (argv.includes('--check')) {
    let disk = null;
    try {
      disk = readFileSync(OUT, 'utf8');
    } catch {}
    if (disk === text) return 0;
    console.error('content/projects/boards/faults.ts differs; run `node scripts/build-lesson-faults.mjs`');
    return 1;
  }
  writeFileSync(OUT, text);
  return 0;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) process.exitCode = main(process.argv.slice(2));

#!/usr/bin/env node
// Descriptor barrel generator.
//
//   node scripts/gen-parts-index.mjs           write src/parts/data/index.generated.ts (only when it changes)
//   node scripts/gen-parts-index.mjs --check   exit 1 when the committed file differs
//
// Lists the flat src/parts/data/*.component.json files, sorted. Subfolders (examples/, tests/) are never listed.

import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dataDir = join(root, 'src', 'parts', 'data');
const outFile = join(dataDir, 'index.generated.ts');
const check = process.argv.includes('--check');

const files = readdirSync(dataDir, { withFileTypes: true })
  .filter((e) => e.isFile() && e.name.endsWith('.component.json'))
  .map((e) => e.name)
  .sort();

const identifier = (file) => {
  const slug = file.slice(0, -'.component.json'.length);
  return slug.replace(/[^a-zA-Z0-9]+(.)?/g, (_, c) => (c ? c.toUpperCase() : '')).replace(/^(\d)/, '_$1');
};

const names = files.map(identifier);
const dup = names.find((n, i) => names.indexOf(n) !== i);
if (dup) {
  console.error(`two descriptor files give the import name ${dup}`);
  process.exit(1);
}

const out = [
  '// Generated by scripts/gen-parts-index.mjs. Do not edit; run `node scripts/gen-parts-index.mjs`.',
  ...files.map((f, i) => `import ${names[i]} from "./${f}" with { type: "json" };`),
  '',
  `export const GENERATED_DESCRIPTORS: readonly unknown[] = [${names.join(', ')}];`,
  '',
].join('\n');

const current = existsSync(outFile) ? readFileSync(outFile, 'utf8') : null;
if (check) {
  if (current !== out) {
    console.error('src/parts/data/index.generated.ts is out of date; run `node scripts/gen-parts-index.mjs`');
    process.exit(1);
  }
} else if (current !== out) {
  writeFileSync(outFile, out);
}

const entries = join(root, 'scripts', 'gen-part-entries.mjs');
if (existsSync(entries)) {
  execFileSync(process.execPath, check ? [entries, '--check'] : [entries], { stdio: 'inherit' });
}

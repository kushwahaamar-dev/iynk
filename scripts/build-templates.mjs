#!/usr/bin/env node
// Builds the template projects of the labs board (T-B12-09a).
//
//   node scripts/build-templates.mjs (--group <arduino|esp|other|fpga> | --all) [--check]
//
// A group lists its boards in content/projects/boards/<group>/boards.json ({ "boards": ["uno-r3", ...] }); a missing
// file or an empty list is an empty group. The script converts those boards in memory, writes one <id>.project.json
// per lesson and board tour next to the list, and the group's index.ts. With `--check` it writes nothing and compares
// the bytes on disk. It never writes outside the group folder. Exit 0 when done (or when the files match), 1 on a
// failed conversion, an unknown board or a difference, 2 on bad arguments.

import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { toCanonicalText } from '../src/project/normalize.ts';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const GROUPS = ['arduino', 'esp', 'other', 'fpga'];
const INDEX = 'index.ts';
const SUFFIX = '.project.json';

const groupDir = (group) => join(root, 'content', 'projects', 'boards', group);

function parseArgs(argv) {
  const args = { groups: null, check: false };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--all') args.groups = GROUPS;
    else if (argv[i] === '--group' && GROUPS.includes(argv[i + 1])) args.groups = [argv[++i]];
    else if (argv[i] === '--check') args.check = true;
    else return null;
  }
  return args.groups ? args : null;
}

function boardsOf(group) {
  const file = join(groupDir(group), 'boards.json');
  if (!existsSync(file)) return [];
  const { boards } = JSON.parse(readFileSync(file, 'utf8'));
  return boards ?? [];
}

const localized = (text) => (typeof text === 'string' ? { en: text } : text);

function entryOf({ project }, language) {
  const { guide } = project;
  if (guide?.kind !== 'lesson' && guide?.kind !== 'tour') throw new Error(`${project.id}: a ${guide?.kind} guide is not a template`);
  const catalogue = project.provenance.origin.catalogue;
  const lesson = guide.kind === 'lesson';
  return {
    id: project.id,
    title: localized(guide.title),
    board: catalogue.id,
    kind: guide.kind,
    order: lesson ? guide.order : 0,
    level: lesson ? (guide.level ?? null) : null,
    stepCount: (lesson ? guide.steps : guide.assembly)?.length ?? 0,
    language,
    catalogue: { lab: 'board', id: catalogue.id, child: catalogue.child ?? null },
  };
}

function indexText(group, entries) {
  const imports = ["import type { TemplateEntry } from '@/project/guided/plan';"];
  if (entries.length > 0) imports.unshift("import type { Project } from '@/project/generated/types';");
  const rows = entries.map((entry) => {
    const fields = Object.entries(entry).map(([key, value]) => `    ${key}: ${JSON.stringify(value)},`);
    const load = `() => import(${JSON.stringify(`./${entry.id}${SUFFIX}`)}).then((m) => m.default as unknown as Project)`;
    return `  {\n${fields.join('\n')}\n    load: ${load},\n  },`;
  });
  return [
    '// Generated by scripts/build-templates.mjs. Do not edit; run `npm run templates`.',
    ...imports,
    '',
    `export const ${group}Templates: readonly TemplateEntry[] = [${rows.length > 0 ? `\n${rows.join('\n')}\n` : ''}];`,
    '',
  ].join('\n');
}

/** The files of one group: path inside the group folder to text. */
function filesOf(group, boards, converted) {
  const order = (board) => boards.indexOf(board);
  const rows = converted
    .filter(({ item }) => boards.includes(item.replace(/^board\//, '')))
    .map((row) => ({ row, board: row.item.replace(/^board\//, '') }));
  const language = (board) =>
    rows.find((r) => r.board === board && r.row.project.guide.kind === 'lesson')?.row.project.sources[0]?.language ?? 'arduino-cpp';
  const entries = rows.map(({ row, board }) => entryOf(row, language(board)));
  const sorted = entries
    .map((entry, i) => ({ entry, row: rows[i].row }))
    .sort((a, b) => order(a.entry.board) - order(b.entry.board) || a.entry.order - b.entry.order || (a.entry.id < b.entry.id ? -1 : 1));
  const files = new Map(sorted.map(({ entry, row }) => [`${entry.id}${SUFFIX}`, `${toCanonicalText(row.project)}\n`]));
  files.set(INDEX, indexText(group, sorted.map(({ entry }) => entry)));
  return files;
}

function onDisk(group) {
  const dir = groupDir(group);
  if (!existsSync(dir)) return new Map();
  const names = readdirSync(dir).filter((name) => name === INDEX || name.endsWith(SUFFIX));
  return new Map(names.map((name) => [name, readFileSync(join(dir, name), 'utf8')]));
}

function differences(expected, found) {
  const out = [];
  for (const [name, text] of expected) {
    if (!found.has(name)) out.push(`${name} is missing`);
    else if (found.get(name) !== text) out.push(`${name} differs`);
  }
  for (const name of found.keys()) if (!expected.has(name)) out.push(`${name} is not generated`);
  return out;
}

function write(group, expected) {
  const dir = groupDir(group);
  mkdirSync(dir, { recursive: true });
  for (const name of onDisk(group).keys()) if (!expected.has(name)) rmSync(join(dir, name));
  for (const [name, text] of expected) writeFileSync(join(dir, name), text);
}

export async function main(argv) {
  const args = parseArgs(argv);
  if (!args) {
    console.error('usage: node scripts/build-templates.mjs (--group <arduino|esp|other|fpga> | --all) [--check]');
    return 2;
  }
  const boardsByGroup = new Map(args.groups.map((group) => [group, boardsOf(group)]));
  const wanted = [...new Set([...boardsByGroup.values()].flat())];

  let converted = [];
  if (wanted.length > 0) {
    const { listItems } = await import('./convert-io.mjs');
    const known = new Set(listItems().filter((i) => i.lab === 'board').map((i) => i.id));
    const unknown = wanted.filter((id) => !known.has(id));
    if (unknown.length > 0) {
      console.error(`not a catalogue board: ${unknown.join(', ')}`);
      return 1;
    }
    const { loadSources } = await import('./convert-catalogue.mjs');
    const { convertAll } = await import('../src/project/convert/index.ts');
    const { items, sources, ctx, plan } = await loadSources(wanted.map((id) => ({ lab: 'board', id })));
    const result = convertAll(items, sources, ctx, plan);
    const failed = result.report.items.filter((item) => item.status === 'failed');
    for (const item of failed) {
      console.error(`failed: ${item.lab}/${item.id}`);
      for (const reason of item.reasons.filter((r) => /invalid|stopped/.test(r.message))) console.error(`  ${reason.message}`);
    }
    if (failed.length > 0) return 1;
    converted = result.projects;
  }

  let status = 0;
  for (const [group, boards] of boardsByGroup) {
    const expected = filesOf(group, boards, converted);
    console.log(`${group}: ${expected.size - 1} templates from ${boards.length} boards`);
    if (args.check) {
      const changes = differences(expected, onDisk(group));
      for (const change of changes) console.error(`content/projects/boards/${group}/${change}`);
      if (changes.length > 0) status = 1;
    } else {
      write(group, expected);
    }
  }
  return status;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  process.exitCode = await main(process.argv.slice(2));
}

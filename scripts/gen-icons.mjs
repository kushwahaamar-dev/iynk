async function regularPaths(glyph) {
  const defs = await import(pathToFileURL(join(ROOT, "node_modules/@phosphor-icons/react/dist/defs", `${glyph}.es.js`)));
  const regular = defs.default.get("regular");
  const parts = [regular.props.children].flat();
  for (const part of parts) {
    if (part.type !== "path" || Object.keys(part.props).join() !== "d") {
      throw new Error(`${glyph}: regular weight holds more than plain paths`);
    }
  }
  return parts.map((part) => part.props.d);
}

export async function generate() {
  const rows = [];
  for (const [name, glyph] of Object.entries(GLYPHS)) {
    rows.push(`  ${JSON.stringify(name)}: ${JSON.stringify(await regularPaths(glyph))},`);
  }
  return [
    "// Generated by scripts/gen-icons.mjs. Do not edit; run `npm run icons`.",
    "export const ICON_PATHS = {",
    ...rows,
    "} as const;",
    "",
  ].join("\n");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const flag = process.argv.indexOf("--out");
  const out = flag === -1 ? DEFAULT_OUT : resolve(process.argv[flag + 1]);
  try {
    writeFileSync(out, await generate());
  } catch (error) {
    console.error(error.message);
    process.exit(1);
  }
}

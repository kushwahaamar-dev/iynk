export function glyph(ch: string): number[] {
  return GLYPHS[ch] ?? GLYPHS[ch.toUpperCase()] ?? GLYPHS['?'];
}

/** One character as 25 brightness values (0 or 9), row major. */
export function charPixels(ch: string): number[] {
  return glyph(ch).flatMap((row) => [4, 3, 2, 1, 0].map((b) => ((row >> b) & 1) * 9));
}

/** Column strip for scrolling: blank lead-in, each glyph plus a one-column gap, blank tail. */
export function scrollColumns(text: string): number[] {
  const cols: number[] = [0, 0, 0, 0, 0];
  for (const ch of text) {
    const g = glyph(ch);
    for (let c = 4; c >= 0; c--) cols.push(g.reduce((acc, row, r) => acc | (((row >> c) & 1) << r), 0));
    cols.push(0);
  }
  return cols;
}

/** The 5x5 window of a column strip starting at `offset`. */
export function scrollFrame(cols: number[], offset: number): number[] {
  const px = new Array(25).fill(0);
  for (let x = 0; x < 5; x++) {
    const col = cols[offset + x] ?? 0;
    for (let y = 0; y < 5; y++) if ((col >> y) & 1) px[y * 5 + x] = 9;
  }
  return px;
}
